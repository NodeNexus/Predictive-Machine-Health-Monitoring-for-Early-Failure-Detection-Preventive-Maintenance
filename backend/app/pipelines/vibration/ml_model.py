"""Runtime wrapper around the trained Vibration ML V1 classifier
(models/vibration/vibration_baseline_v1.joblib).

MODEL TYPE: a derived-label trajectory classifier, NOT an independently
validated fault detector. Its three classes (healthy/degrading/severe) are
categories generated by the documented statistical labeling rule in
models/vibration/vibration_task_definition.json - RMS and kurtosis
participate directly in that rule AND are two of this model's own input
features. Its 1.0 test F1 is therefore NOT independently validated
fault-detection performance (see models/vibration/model_metadata.json's
IMPORTANT_tautology_finding and models/vibration/confidence_analysis.json).
Do not present healthy/degrading/severe as certified physical diagnoses -
they are model states derived from the IMS trajectory labeling scheme.

This module is deliberately isolated from VibrationAnalyzer: the
deterministic vibration feature pipeline (RMS, kurtosis, crest factor,
FFT, spectral features, octave analysis, baseline, anomaly detection) is
unchanged and remains authoritative for anomaly/health/fusion. This module
produces CONTEXTUAL evidence only, consuming the already-produced feature
representation (no duplicate feature extraction) - its output never feeds
baseline calibration, the anomaly detector, fusion, or event generation.

Loads the model exactly once (joblib.load happens in __init__, never per
window). If the model/metadata files are missing or inference raises for
any reason, `.available` is False (or the failing call returns None) and
the caller is expected to degrade gracefully - never let an ML failure
interrupt the deterministic vibration loop or crash the demo.
"""
from __future__ import annotations

from pathlib import Path

from app.core.logging import get_logger
from app.pipelines.vibration.features import VibrationFeatures

logger = get_logger("vibration.ml_model")

REPO_ROOT = Path(__file__).resolve().parents[4]
DEFAULT_MODEL_PATH = REPO_ROOT / "models" / "vibration" / "vibration_baseline_v1.joblib"
DEFAULT_METADATA_PATH = REPO_ROOT / "models" / "vibration" / "model_metadata.json"


class VibrationMLModel:
    """Loads once; call `.predict(features)` per processed window, where
    `features` is the VibrationFeatures instance already produced by
    VibrationAnalyzer/extract_vibration_features for that window."""

    def __init__(self, model_path: Path = DEFAULT_MODEL_PATH, metadata_path: Path = DEFAULT_METADATA_PATH) -> None:
        self.available = False
        self.class_names: list[str] = []
        self.feature_columns: list[str] = []
        self.model_version: str | None = None
        self._model = None
        self._scaler = None

        try:
            import json

            import joblib

            if not model_path.is_file():
                raise FileNotFoundError(f"Vibration ML model not found: {model_path}")
            if not metadata_path.is_file():
                raise FileNotFoundError(f"Vibration ML metadata not found: {metadata_path}")

            metadata = json.loads(metadata_path.read_text(encoding="utf-8"))
            self.class_names = metadata["class_names"]
            self.feature_columns = metadata["feature_columns"]
            self.model_version = metadata["model_version"]

            bundle = joblib.load(model_path)
            self._model = bundle["model"]
            self._scaler = bundle.get("scaler")  # None for the exported RandomForest (scale-invariant)

            self.available = True
            logger.info(f"Vibration ML model loaded ({self.model_version}, classes={self.class_names})")
        except Exception as exc:  # noqa: BLE001 - any failure here must not be fatal
            logger.warning(f"Vibration ML model unavailable, continuing without it: {exc}")

    def predict(self, features: VibrationFeatures) -> dict | None:
        """`features` is the same VibrationFeatures object already produced
        by the deterministic analyzer for this window - never re-extracted
        here. Returns a raw prediction dict, or None if the model isn't
        available, the feature set doesn't match what the model expects, or
        inference fails for any reason - never raises."""
        if not self.available:
            return None
        try:
            import numpy as np

            row = [getattr(features, col) for col in self.feature_columns]
            X = np.array([row], dtype=np.float64)
            if self._scaler is not None:
                X = self._scaler.transform(X)

            probs = self._model.predict_proba(X)[0]
            top_idx = int(np.argmax(probs))
            return {
                "predicted_class": self.class_names[top_idx],
                "confidence": float(probs[top_idx]),
                "probabilities": {name: float(p) for name, p in zip(self.class_names, probs)},
                "model_version": self.model_version,
            }
        except Exception as exc:  # noqa: BLE001 - inference/feature-mismatch failure must not crash the caller
            logger.warning(f"Vibration ML inference failed on a window, skipping: {exc}")
            return None
